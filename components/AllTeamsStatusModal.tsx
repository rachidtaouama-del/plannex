    const initialDayIdx = useMemo(() => {
        if (!schedulingDate || shutdownDays.length === 0) return 0;
        const target = schedulingDate.split('T')[0];
        const idx = shutdownDays.indexOf(target);
        return idx >= 0 ? idx : 0;
    }, [schedulingDate, shutdownDays]);

