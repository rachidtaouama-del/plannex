// ─── helpers ────────────────────────────────────────────────────────────────

const fmt = (d: Date) =>
    d.toLocaleTimeString('fr-FR', { hour: '2-digit', minute: '2-digit' });

// FIX #2: Use LOCAL date components to avoid UTC offset producing wrong day
const isoDate = (d: Date): string => {
    const y = d.getFullYear();
    const mo = String(d.getMonth() + 1).padStart(2, '0');
    const da = String(d.getDate()).padStart(2, '0');
    return `${y}-${mo}-${da}`;
};

const fmtDate = (iso: string) => {
    // FIX #2: parse as LOCAL date, not UTC
    const d = new Date(iso + 'T00:00:00');
    return d.toLocaleDateString('fr-FR', { weekday: 'short', day: '2-digit', month: 'short' });
};

// FIX #2: getDaysInRange uses local dates, not UTC
function getDaysInRange(startIso: string, endIso: string): string[] {
    const days: string[] = [];
    // Parse as LOCAL time
    const cur = new Date(startIso + 'T00:00:00');
    const fin = new Date(endIso + 'T00:00:00');
    while (cur <= fin) {
        days.push(isoDate(cur));
        cur.setDate(cur.getDate() + 1);
    }
    return days;
}

function overlapHours(
    taskStart: Date, taskEnd: Date,
    winStart: Date, winEnd: Date
): number {
    const ms = Math.max(0,
        Math.min(taskEnd.getTime(), winEnd.getTime()) -
        Math.max(taskStart.getTime(), winStart.getTime())
    );
    return ms / 3_600_000;
}

